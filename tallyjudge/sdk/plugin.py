import importlib
import pkgutil
from collections.abc import Callable, Iterator, Mapping
from dataclasses import dataclass, field
from types import MappingProxyType, ModuleType
from typing import Any, Literal

type Dependencies = Mapping[str, Literal["language_model", "embedding_model", "client"]]


@dataclass(frozen=True)
class PluginSpec:
    """One registry row: a plugin ID, its kind and the factory that builds it."""

    id: str
    kind: str
    api_version: int
    factory: str | Callable[..., Any]
    required_distributions: tuple[str, ...] = ()
    dependencies: Dependencies = field(default_factory=dict)
    install_extra: str | None = None
    optional_dependencies: Dependencies = field(default_factory=dict)
    produces: str | None = None

    def __post_init__(self) -> None:
        if self.optional_dependencies.keys() & self.dependencies.keys():
            raise ValueError(
                f"Dependency declared as both required and optional: {self.id}"
            )
        object.__setattr__(
            self,
            "optional_dependencies",
            MappingProxyType(dict(self.optional_dependencies)),
        )
        object.__setattr__(
            self, "dependencies", MappingProxyType(dict(self.dependencies))
        )


@dataclass(frozen=True)
class Plugin:
    """What a plugin class declares about itself; manifests are generated from it."""

    kind: str
    dependencies: Dependencies = field(default_factory=dict)
    optional_dependencies: Dependencies = field(default_factory=dict)
    requires: tuple[str, ...] = ()
    extra: str | None = None
    produces: str | None = None


@dataclass(frozen=True)
class KindSpec:
    """A plugin kind defined by a package, with the contract its plugins must satisfy."""

    kind: str
    contract: str | type


def plugin_spec(factory: type) -> PluginSpec:
    declared: Plugin = factory.__dict__["plugin"]
    plugin_id = getattr(factory, "plugin_id", None) or factory.spec.id
    return PluginSpec(
        plugin_id,
        declared.kind,
        1,
        f"{factory.__module__}:{factory.__qualname__}",
        declared.requires,
        declared.dependencies,
        declared.extra,
        declared.optional_dependencies,
        declared.produces,
    )


def _modules(package: str) -> Iterator[ModuleType]:
    root = importlib.import_module(package)
    for info in pkgutil.walk_packages(root.__path__, package + "."):
        yield importlib.import_module(info.name)


def declared_plugins(package: str) -> tuple[PluginSpec, ...]:
    specs = [
        plugin_spec(value)
        for module in _modules(package)
        for value in vars(module).values()
        if isinstance(value, type)
        and value.__module__ == module.__name__
        and "plugin" in value.__dict__
    ]
    return tuple(sorted(specs, key=lambda spec: spec.id))


def declared_kinds(package: str) -> tuple[KindSpec, ...]:
    kinds = {
        value.kind: value
        for module in _modules(package)
        for value in vars(module).values()
        if isinstance(value, KindSpec)
    }
    return tuple(kinds[name] for name in sorted(kinds))


def manifest_source(package: str, name: str = "PLUGINS") -> str:
    rows = []
    for kind in declared_kinds(package):
        contract = kind.contract
        if isinstance(contract, type):
            contract = f"{contract.__module__}:{contract.__qualname__}"
        rows.append(f"    KindSpec({kind.kind!r}, {contract!r}),\n")
    names = "KindSpec, PluginSpec" if rows else "PluginSpec"
    for spec in declared_plugins(package):
        fields = [
            repr(spec.id),
            repr(spec.kind),
            repr(spec.api_version),
            repr(spec.factory),
        ]
        if spec.required_distributions:
            fields.append(f"required_distributions={spec.required_distributions!r}")
        if spec.dependencies:
            fields.append(f"dependencies={dict(spec.dependencies)!r}")
        if spec.install_extra:
            fields.append(f"install_extra={spec.install_extra!r}")
        if spec.optional_dependencies:
            fields.append(f"optional_dependencies={dict(spec.optional_dependencies)!r}")
        if spec.produces:
            fields.append(f"produces={spec.produces!r}")
        rows.append(f"    PluginSpec({', '.join(fields)}),\n")
    return (
        f'"""Generated by `tallyjudge manifest {package}` from the plugin classes. Do not edit."""\n\n'
        f"from tallyjudge.sdk.plugin import {names}\n\n"
        f"{name} = (\n{''.join(rows)})\n"
    )
